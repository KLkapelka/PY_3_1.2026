# картеж, сведения о складе
sklad = ("Мироходец", "Санкт-Петербург, Гражданская ул., 8", "15.07.2026")

# список, номера поставок
postavki = ["П-41", "П-42", "П-43", "П-44", "П-45", "П-46"]

# множество, уникальные артикулоы принятых товаров
artikuly = {"A-100", "A-132", "A-154", "A-181"}

# словарь, артикул -> название товара
tovary = {
    "A-100": "Футболка «Мастерская 47»",
    "A-132": "Худи «Искра»",
    "A-154": "Брюки «Мироходец»",
    "A-181": "Кружка"
}

print(f"Склад: «{sklad[0]}», {sklad[1]}, инвентаризация {sklad[2]}")
print(f"Поставки в порядке поступления: {', '.join(postavki)}")
print(f"Принятые артикулы: {', '.join(artikuly)}")
print("Товары: " + "; ".join([f"{k} - «{v}»" for k, v in tovary.items()]))

# добавление новой поставки в список
postavki.append("П-47")

# проверка наличия артикула среди принятых товаров
artikul_dlya_proverki = "A-154"
prinyat = artikul_dlya_proverki in artikuly

# получение названия товара по артикулу из словаря
artikul_dlya_poiska = "A-132"
nazvanie = tovary[artikul_dlya_poiska]

# результаты после изменений
print(f"\nПосле добавления поставки: {', '.join(postavki)}")
print(f"Товар с артикулом {artikul_dlya_proverki} принят: {'да' if prinyat else 'нет'}")
print(f"Название товара {artikul_dlya_poiska}: «{nazvanie}»")
