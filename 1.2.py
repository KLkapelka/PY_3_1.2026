# список с повторениями
line = ["1", "2", "1", "4", "1", "6", "7", "8", "9", "10", "10", "12"]

# множество -> без дубликатов
set_line = set(line)

# исходный список и полученное множество
print(f"Исходный список: {line}")
print(f"Множество без повторов: {set_line}")

# сравнение кол-во элементов в обеих коллекциях
print(f"Элементов в списке: {len(line)}")
print(f"Элементов во множестве: {len(set_line)}")
